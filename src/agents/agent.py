"""
Agent representation for the multi-agent warehouse.

Each agent maintains:
    - its identity,
    - current position,
    - assigned tasks,
    - execution state,
    - original plan,
    - current plan.

The original plan is preserved so that the repair subsystem can
measure exactly how many agents had to change their plans after
a disruption.
"""

from __future__ import annotations

from copy import deepcopy
from dataclasses import dataclass, field
from enum import Enum
from typing import Iterable, Optional, Sequence, Tuple

from .task import Position, Task, TaskStatus


# ---------------------------------------------------------------------------
# Type aliases
# ---------------------------------------------------------------------------

# A space-time state is:
#     (row, column, timestep)
SpaceTimeState = Tuple[int, int, int]

Trajectory = list[SpaceTimeState]


# ---------------------------------------------------------------------------
# Agent status
# ---------------------------------------------------------------------------

class AgentStatus(Enum):
    """
    Current operational state of a robot.
    """

    IDLE = "idle"
    MOVING = "moving"
    PICKING = "picking"
    DELIVERING = "delivering"
    WAITING = "waiting"
    FAILED = "failed"
    COMPLETED = "completed"


# ---------------------------------------------------------------------------
# Agent
# ---------------------------------------------------------------------------

@dataclass
class Agent:
    """
    Represents one autonomous warehouse robot.

    Parameters
    ----------
    agent_id:
        Unique identifier.

    start_position:
        Initial grid position.

    tasks:
        Tasks assigned to the agent.

    move_cost:
        Cost of moving one grid cell.

    wait_cost:
        Cost of waiting for one timestep.
    """

    agent_id: str
    start_position: Position

    tasks: list[Task] = field(default_factory=list)

    move_cost: float = 1.0
    wait_cost: float = 1.0

    # Current physical position.
    current_position: Position = field(init=False)

    # Current task index in the task list.
    current_task_index: int = field(default=0, init=False)

    # Current trajectory being executed.
    current_plan: Trajectory = field(default_factory=list, init=False)

    # Original trajectory generated by the initial planner.
    original_plan: Trajectory = field(default_factory=list, init=False)

    # Number of times this agent's plan has been replaced by repair.
    repair_count: int = field(default=0, init=False)

    # Whether this agent has ever had its original plan modified.
    plan_modified: bool = field(default=False, init=False)

    # Current agent status.
    status: AgentStatus = field(
        default=AgentStatus.IDLE,
        init=False,
    )

    # Current timestep associated with execution.
    current_time: int = field(default=0, init=False)

    # -----------------------------------------------------------------------
    # Initialization
    # -----------------------------------------------------------------------

    def __post_init__(self) -> None:
        """Validate and initialize the agent."""
        self._validate_position(
            self.start_position,
            "start_position",
        )

        if self.move_cost <= 0:
            raise ValueError(
                "move_cost must be greater than zero."
            )

        if self.wait_cost <= 0:
            raise ValueError(
                "wait_cost must be greater than zero."
            )

        self.current_position = self.start_position

        # Make sure a mutable list is stored internally.
        self.tasks = list(self.tasks)

    # -----------------------------------------------------------------------
    # Task management
    # -----------------------------------------------------------------------

    def add_task(self, task: Task) -> None:
        """
        Add a task to the agent's task queue.

        Parameters
        ----------
        task:
            Task to assign.
        """
        if self.status == AgentStatus.FAILED:
            raise RuntimeError(
                f"Cannot assign a task to failed agent '{self.agent_id}'."
            )

        self.tasks.append(task)

        if self.status == AgentStatus.IDLE:
            self.status = AgentStatus.MOVING

    def add_tasks(self, tasks: Iterable[Task]) -> None:
        """
        Add multiple tasks.
        """
        for task in tasks:
            self.add_task(task)

    @property
    def current_task(self) -> Optional[Task]:
        """
        Return the currently active task.

        Returns None if all assigned tasks are finished.
        """
        if self.current_task_index >= len(self.tasks):
            return None

        return self.tasks[self.current_task_index]

    @property
    def has_pending_tasks(self) -> bool:
        """
        Return True when at least one task remains unfinished.
        """
        return any(
            not task.is_completed
            for task in self.tasks
        )

    @property
    def all_tasks_completed(self) -> bool:
        """
        Return True when all assigned tasks are complete.
        """
        return bool(self.tasks) and all(
            task.is_completed
            for task in self.tasks
        )

    # -----------------------------------------------------------------------
    # Plan management
    # -----------------------------------------------------------------------

    def set_plan(
        self,
        trajectory: Sequence[SpaceTimeState],
        *,
        preserve_as_original: bool = False,
        mark_as_repair: bool = False,
    ) -> None:
        """
        Set the agent's trajectory.

        Parameters
        ----------
        trajectory:
            Sequence of (row, column, time) states.

        preserve_as_original:
            If True, this trajectory becomes the baseline original plan.

            This should normally be used only by the initial planner.

        mark_as_repair:
            If True, this update is considered a repair modification.
        """
        validated_plan = self._validate_trajectory(trajectory)

        self.current_plan = deepcopy(validated_plan)

        if preserve_as_original:
            self.original_plan = deepcopy(validated_plan)
            self.plan_modified = False
            self.repair_count = 0

        if mark_as_repair:
            self.repair_count += 1

            if self.current_plan != self.original_plan:
                self.plan_modified = True

        if self.current_plan:
            first_position = (
                self.current_plan[0][0],
                self.current_plan[0][1],
            )

            # The trajectory does not forcibly change the physical
            # position of the robot; only the first plan position is
            # checked against the current execution state by the simulator.
            if self.current_position != first_position:
                # No exception here because a repaired trajectory may
                # intentionally begin at the agent's current state.
                pass

    def set_initial_plan(
        self,
        trajectory: Sequence[SpaceTimeState],
    ) -> None:
        """
        Store the trajectory generated by the initial planner.

        This establishes the baseline against which repair impact
        will be measured.
        """
        self.set_plan(
            trajectory,
            preserve_as_original=True,
            mark_as_repair=False,
        )

    def repair_plan(
        self,
        trajectory: Sequence[SpaceTimeState],
    ) -> None:
        """
        Replace the current plan with a repaired trajectory.

        The original plan is intentionally preserved.
        """
        self.set_plan(
            trajectory,
            preserve_as_original=False,
            mark_as_repair=True,
        )

    def reset_to_original_plan(self) -> None:
        """
        Restore the original trajectory.

        Mainly useful for experiments and controlled comparisons.
        """
        self.current_plan = deepcopy(self.original_plan)
        self.plan_modified = False

    def has_plan(self) -> bool:
        """Return True when the agent has a trajectory."""
        return len(self.current_plan) > 0

    def has_original_plan(self) -> bool:
        """Return True when an original trajectory exists."""
        return len(self.original_plan) > 0

    # -----------------------------------------------------------------------
    # Trajectory access
    # -----------------------------------------------------------------------

    def planned_position_at(
        self,
        timestep: int,
    ) -> Optional[Position]:
        """
        Return the position planned for a specific timestep.

        The trajectory is expected to contain one state per timestep,
        but the method also handles trajectories that do not start at
        timestep zero.
        """
        for row, col, time in self.current_plan:
            if time == timestep:
                return (row, col)

        return None

    def planned_state_at(
        self,
        timestep: int,
    ) -> Optional[SpaceTimeState]:
        """
        Return the full space-time state for a timestep.
        """
        for state in self.current_plan:
            if state[2] == timestep:
                return state

        return None

    def remaining_plan(self) -> Trajectory:
        """
        Return the portion of the plan at or after current_time.
        """
        return [
            state
            for state in self.current_plan
            if state[2] >= self.current_time
        ]

    def future_positions(self) -> list[Position]:
        """
        Return future positions from the current trajectory.
        """
        return [
            (row, col)
            for row, col, time in self.current_plan
            if time >= self.current_time
        ]

    # -----------------------------------------------------------------------
    # Execution state
    # -----------------------------------------------------------------------

    def update_position(
        self,
        position: Position,
        timestep: Optional[int] = None,
    ) -> None:
        """
        Update the agent's actual physical position.

        Parameters
        ----------
        position:
            New grid position.

        timestep:
            Optional simulation timestep.
        """
        self._validate_position(
            position,
            "position",
        )

        if self.status == AgentStatus.FAILED:
            raise RuntimeError(
                f"Failed agent '{self.agent_id}' cannot move."
            )

        self.current_position = position

        if timestep is not None:
            if timestep < self.current_time:
                raise ValueError(
                    "Simulation time cannot move backwards."
                )

            self.current_time = timestep

        if self.has_pending_tasks:
            self.status = AgentStatus.MOVING
        else:
            self.status = AgentStatus.COMPLETED

    def advance_time(self, timestep: int) -> None:
        """
        Advance the agent's internal clock without moving.
        """
        if timestep < self.current_time:
            raise ValueError(
                "Simulation time cannot move backwards."
            )

        self.current_time = timestep

    def mark_waiting(self) -> None:
        """
        Mark the agent as waiting for the current timestep.
        """
        if self.status != AgentStatus.FAILED:
            self.status = AgentStatus.WAITING

    def mark_failed(self) -> None:
        """
        Permanently mark the agent as failed.
        """
        self.status = AgentStatus.FAILED

    def mark_picking(self) -> None:
        """
        Mark the agent as performing a pickup operation.
        """
        if self.status != AgentStatus.FAILED:
            self.status = AgentStatus.PICKING

    def mark_delivering(self) -> None:
        """
        Mark the agent as performing a delivery operation.
        """
        if self.status != AgentStatus.FAILED:
            self.status = AgentStatus.DELIVERING

    def mark_completed(self) -> None:
        """
        Mark the agent as completed.
        """
        self.status = AgentStatus.COMPLETED

    # -----------------------------------------------------------------------
    # Task progression
    # -----------------------------------------------------------------------

    def start_current_task(self) -> None:
        """
        Start the current task.
        """
        task = self.current_task

        if task is None:
            self.mark_completed()
            return

        if task.status == TaskStatus.PENDING:
            task.start()

        self.status = AgentStatus.MOVING

    def complete_current_task(self) -> None:
        """
        Move to the next task after completing the current task.
        """
        task = self.current_task

        if task is None:
            self.mark_completed()
            return

        if not task.is_completed:
            raise RuntimeError(
                f"Task '{task.task_id}' is not completed."
            )

        self.current_task_index += 1

        if self.current_task_index >= len(self.tasks):
            self.mark_completed()
        else:
            self.start_current_task()

    # -----------------------------------------------------------------------
    # Plan comparison
    # -----------------------------------------------------------------------

    def has_plan_changed(self) -> bool:
        """
        Return True if the current trajectory differs from the
        original trajectory.
        """
        return self.current_plan != self.original_plan

    def modified_state_count(self) -> int:
        """
        Count how many states differ between the current and original plan.

        This is useful as a secondary repair metric.

        Note:
            The primary project metric is the number of agents modified,
            not the number of trajectory states modified.
        """
        max_length = max(
            len(self.current_plan),
            len(self.original_plan),
        )

        differences = 0

        for index in range(max_length):
            current = (
                self.current_plan[index]
                if index < len(self.current_plan)
                else None
            )

            original = (
                self.original_plan[index]
                if index < len(self.original_plan)
                else None
            )

            if current != original:
                differences += 1

        return differences

    # -----------------------------------------------------------------------
    # Utility / validation
    # -----------------------------------------------------------------------

    @staticmethod
    def _validate_position(
        position: Position,
        field_name: str,
    ) -> None:
        """
        Validate a 2D grid position.
        """
        if (
            not isinstance(position, tuple)
            or len(position) != 2
            or not all(isinstance(value, int) for value in position)
        ):
            raise TypeError(
                f"{field_name} must be a tuple of two integers. "
                f"Received: {position!r}"
            )

    @staticmethod
    def _validate_trajectory(
        trajectory: Sequence[SpaceTimeState],
    ) -> Trajectory:
        """
        Validate a trajectory.

        Each state must be:

            (row, column, timestep)

        with all three components being integers.
        """
        validated: Trajectory = []

        previous_time: Optional[int] = None

        for index, state in enumerate(trajectory):
            if (
                not isinstance(state, tuple)
                or len(state) != 3
                or not all(isinstance(value, int) for value in state)
            ):
                raise TypeError(
                    f"Invalid trajectory state at index {index}: "
                    f"{state!r}. Expected (row, column, timestep)."
                )

            row, col, timestep = state

            if row < 0 or col < 0 or timestep < 0:
                raise ValueError(
                    f"Trajectory values cannot be negative: {state!r}"
                )

            if (
                previous_time is not None
                and timestep <= previous_time
            ):
                raise ValueError(
                    "Trajectory timesteps must be strictly increasing."
                )

            previous_time = timestep
            validated.append((row, col, timestep))

        return validated

    def __repr__(self) -> str:
        """
        Human-readable agent representation.
        """
        return (
            f"Agent("
            f"id={self.agent_id!r}, "
            f"position={self.current_position}, "
            f"tasks={len(self.tasks)}, "
            f"status={self.status.value}, "
            f"plan_modified={self.plan_modified}"
            f")"
        )