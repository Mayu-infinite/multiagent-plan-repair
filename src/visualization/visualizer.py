"""
Visualization for the Multi-Agent Plan Repair warehouse simulation.

The visualizer consumes the simulation history generated by:

    src.simulation.simulator.Simulator

It does not perform planning, simulation, conflict detection, or repair.

Supported visual elements
-------------------------
- Warehouse grid
- Static obstacles
- Dynamic obstacles
- Agent positions
- Agent identifiers
- Agent trajectories
- Pickup locations
- Delivery locations
- Plan-modification status
- Simulation timestep

The animation is designed to clearly demonstrate the difference
between the original execution and the locally repaired execution.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Any, Iterable, Mapping, Optional, Sequence

import matplotlib.animation as animation
import matplotlib.pyplot as plt
import numpy as np

from ..agents import Agent
from ..environment import Grid


# ---------------------------------------------------------------------------
# Type aliases
# ---------------------------------------------------------------------------

Position = tuple[int, int]


# ---------------------------------------------------------------------------
# Visualization configuration
# ---------------------------------------------------------------------------

@dataclass
class VisualizationConfig:
    """
    Visualization settings.

    These correspond to the values in configs/*.yaml.
    """

    show_grid: bool = True
    show_static_obstacles: bool = True
    show_dynamic_obstacles: bool = True
    show_agent_paths: bool = True
    show_agent_ids: bool = True
    show_tasks: bool = True

    animate: bool = True
    save_animation: bool = True

    animation_fps: int = 5

    def __post_init__(self) -> None:
        """Validate visualization settings."""
        if self.animation_fps <= 0:
            raise ValueError(
                "animation_fps must be greater than zero."
            )


# ---------------------------------------------------------------------------
# Visualizer
# ---------------------------------------------------------------------------

class WarehouseVisualizer:
    """
    Visualize a multi-agent warehouse simulation.

    Parameters
    ----------
    grid:
        Warehouse grid.

    agents:
        Agents used in the simulation.

    history:
        Optional simulation history produced by Simulator.get_history().

    config:
        Optional visualization configuration.
    """

    def __init__(
        self,
        grid: Grid,
        agents: Sequence[Agent],
        history: Optional[
            Sequence[Mapping[str, Any]]
        ] = None,
        config: Optional[VisualizationConfig] = None,
    ) -> None:
        self.grid = grid
        self.agents = list(agents)

        self.history = list(
            history or []
        )

        self.config = (
            config
            if config is not None
            else VisualizationConfig()
        )

        # Agent lookup for quick access.
        self.agent_by_id: dict[
            str,
            Agent,
        ] = {
            agent.agent_id: agent
            for agent in self.agents
        }

        # Fixed ordering ensures colors/markers remain associated
        # with the same agent throughout an animation.
        self.agent_ids = sorted(
            self.agent_by_id
        )

        # Matplotlib objects are created when a visualization is requested.
        self.figure: Optional[
            plt.Figure
        ] = None

        self.axis: Optional[
            plt.Axes
        ] = None

        self.agent_artists: dict[
            str,
            Any,
        ] = {}

        self.agent_path_artists: dict[
            str,
            Any,
        ] = {}

        self.dynamic_obstacle_artist: Optional[Any] = None

        self.timestep_text: Optional[Any] = None
        self.status_text: Optional[Any] = None

        self._agent_marker_sequence = [
            "o",
            "s",
            "^",
            "D",
            "P",
            "X",
            "*",
            "v",
            "<",
            ">",
        ]

    # -----------------------------------------------------------------------
    # Static visualization
    # -----------------------------------------------------------------------

    def plot(
        self,
        timestep: Optional[int] = None,
        *,
        show: bool = True,
        save_path: Optional[str | Path] = None,
    ) -> plt.Figure:
        """
        Create a static visualization.

        Parameters
        ----------
        timestep:
            Timestep to display.

            If None, the final history frame is displayed.

        show:
            Whether matplotlib should display the figure.

        save_path:
            Optional PNG path.

        Returns
        -------
        matplotlib.figure.Figure
        """
        frame = self._get_frame(
            timestep=timestep
        )

        self.figure, self.axis = plt.subplots(
            figsize=(10, 10)
        )

        self._configure_axis()

        self._draw_static_obstacles()

        if self.config.show_tasks:
            self._draw_task_locations()

        if self.config.show_dynamic_obstacles:
            self._draw_dynamic_obstacles(
                frame
            )

        if self.config.show_agent_paths:
            self._draw_agent_paths()

        self._draw_agents(
            frame
        )

        self._draw_timestep(
            frame
        )

        self._draw_legend()

        self.figure.tight_layout()

        if save_path is not None:
            output = Path(save_path)
            output.parent.mkdir(
                parents=True,
                exist_ok=True,
            )

            self.figure.savefig(
                output,
                dpi=180,
                bbox_inches="tight",
            )

        if show:
            plt.show()

        return self.figure

    # -----------------------------------------------------------------------
    # Animation
    # -----------------------------------------------------------------------

    def animate(
        self,
        *,
        show: bool = True,
        save_path: Optional[str | Path] = None,
        fps: Optional[int] = None,
    ) -> animation.FuncAnimation:
        """
        Create an animation from simulation history.

        Parameters
        ----------
        show:
            Whether to display the animation.

        save_path:
            Optional path for saving the animation.

            A `.gif` extension is recommended.

        fps:
            Animation frames per second.
            Defaults to configured animation_fps.

        Returns
        -------
        matplotlib.animation.FuncAnimation
        """
        if not self.history:
            raise ValueError(
                "Cannot animate an empty simulation history."
            )

        if fps is None:
            fps = self.config.animation_fps

        if fps <= 0:
            raise ValueError(
                "fps must be greater than zero."
            )

        self.figure, self.axis = plt.subplots(
            figsize=(10, 10)
        )

        self._configure_axis()
        self._draw_static_obstacles()

        if self.config.show_tasks:
            self._draw_task_locations()

        self._create_agent_artists()

        # Dynamic obstacle artist is initialized as an empty scatter.
        if self.config.show_dynamic_obstacles:
            self.dynamic_obstacle_artist = self.axis.scatter(
                [],
                [],
                marker="s",
                s=150,
                alpha=0.85,
                label="Dynamic obstacle",
            )

        self.timestep_text = self.axis.text(
            0.02,
            1.02,
            "",
            transform=self.axis.transAxes,
            fontsize=12,
            fontweight="bold",
        )

        self.status_text = self.axis.text(
            0.98,
            1.02,
            "",
            transform=self.axis.transAxes,
            fontsize=10,
            horizontalalignment="right",
        )

        self._draw_legend()

        def init() -> list[Any]:
            """Initialize animation artists."""
            return self._update_frame(
                0
            )

        def update(frame_index: int) -> list[Any]:
            """Update one animation frame."""
            return self._update_frame(
                frame_index
            )

        interval = 1000 / fps

        animation_object = animation.FuncAnimation(
            self.figure,
            update,
            frames=len(self.history),
            init_func=init,
            interval=interval,
            blit=False,
            repeat=False,
        )

        if save_path is not None:
            self.save_animation(
                animation_object,
                save_path,
                fps=fps,
            )

        if show:
            plt.show()

        return animation_object

    # -----------------------------------------------------------------------
    # Save animation
    # -----------------------------------------------------------------------

    def save_animation(
        self,
        animation_object: animation.FuncAnimation,
        save_path: str | Path,
        *,
        fps: Optional[int] = None,
    ) -> Path:
        """
        Save an animation.

        GIF output uses PillowWriter and therefore requires Pillow.

        Supported recommendation:

            results/plots/warehouse_simulation.gif
        """
        if fps is None:
            fps = self.config.animation_fps

        output = Path(
            save_path
        )

        output.parent.mkdir(
            parents=True,
            exist_ok=True,
        )

        suffix = output.suffix.lower()

        if suffix == ".gif":
            try:
                writer = animation.PillowWriter(
                    fps=fps
                )
            except Exception as exc:
                raise RuntimeError(
                    "GIF animation requires Pillow. "
                    "Install it using: pip install pillow"
                ) from exc

            animation_object.save(
                output,
                writer=writer,
            )

        elif suffix in {
            ".mp4",
            ".m4v",
        }:
            try:
                writer = animation.FFMpegWriter(
                    fps=fps
                )

                animation_object.save(
                    output,
                    writer=writer,
                )

            except Exception as exc:
                raise RuntimeError(
                    "MP4 animation requires FFmpeg. "
                    "Use GIF output when FFmpeg is unavailable."
                ) from exc

        else:
            raise ValueError(
                "Unsupported animation format. "
                "Use .gif or .mp4."
            )

        return output

    # -----------------------------------------------------------------------
    # Final frame
    # -----------------------------------------------------------------------

    def plot_final(
        self,
        *,
        show: bool = True,
        save_path: Optional[str | Path] = None,
    ) -> plt.Figure:
        """
        Display the final recorded simulation frame.
        """
        return self.plot(
            timestep=None,
            show=show,
            save_path=save_path,
        )

    # -----------------------------------------------------------------------
    # Original path visualization
    # -----------------------------------------------------------------------

    def plot_original_plans(
        self,
        *,
        show: bool = True,
        save_path: Optional[str | Path] = None,
    ) -> plt.Figure:
        """
        Plot the original trajectories generated by the initial planner.

        This is useful for comparison with the final repaired plans.
        """
        self.figure, self.axis = plt.subplots(
            figsize=(10, 10)
        )

        self._configure_axis()
        self._draw_static_obstacles()

        if self.config.show_tasks:
            self._draw_task_locations()

        if self.config.show_agent_paths:
            for index, agent in enumerate(
                sorted(
                    self.agents,
                    key=lambda item: item.agent_id,
                )
            ):
                positions = [
                    (
                        state[1],
                        state[0],
                    )
                    for state in agent.original_plan
                ]

                if not positions:
                    continue

                x_values = [
                    position[0]
                    for position in positions
                ]

                y_values = [
                    position[1]
                    for position in positions
                ]

                marker = (
                    self._agent_marker_sequence[
                        index
                        % len(self._agent_marker_sequence)
                    ]
                )

                self.axis.plot(
                    x_values,
                    y_values,
                    linestyle="--",
                    linewidth=1.5,
                    marker=marker,
                    markersize=3,
                    alpha=0.65,
                    label=f"{agent.agent_id} original",
                )

        self.axis.set_title(
            "Original Multi-Agent Plans"
        )

        self._draw_legend()

        self.figure.tight_layout()

        if save_path is not None:
            output = Path(save_path)
            output.parent.mkdir(
                parents=True,
                exist_ok=True,
            )

            self.figure.savefig(
                output,
                dpi=180,
                bbox_inches="tight",
            )

        if show:
            plt.show()

        return self.figure

