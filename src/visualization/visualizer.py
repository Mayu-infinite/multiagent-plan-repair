    def save_comparison(
        self,
        output_directory: str | Path = "results/plots",
        *,
        show: bool = False,
    ) -> dict[str, Path]:
        """
        Save original-plan and repaired-plan comparison figures.

        Returns
        -------
        dict
            Paths of generated files.
        """
        output_dir = Path(
            output_directory
        )

        output_dir.mkdir(
            parents=True,
            exist_ok=True,
        )

        original_path = (
            output_dir
            / "original_plans.png"
        )

        repaired_path = (
            output_dir
            / "repaired_plans.png"
        )

        self.plot_original_plans(
            show=show,
            save_path=original_path,
        )

        plt.close()

        self.plot_repaired_plans(
            show=show,
            save_path=repaired_path,
        )

        plt.close()

        return {
            "original": original_path,
            "repaired": repaired_path,
        }